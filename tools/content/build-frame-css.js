let css = tokens;
const plain = [], medias = new Map();
for (const [key, variants] of rules) {
  const [media, sel] = [key.slice(0, key.indexOf('|')), key.slice(key.indexOf('|') + 1)];
  const emit = (selector, decls) => {
    if (media) (medias.get(media) || medias.set(media, []).get(media)).push(`  ${selector} { ${decls} }`);
    else plain.push(`${selector} { ${decls} }`);
  };
  if (variants.size === 1) { emit(sel, [...variants.keys()][0]); continue; }
  // the same class means different things on different pages: scope each variant to its pages
  for (const [decls, pagesSet] of variants) {
    emit([...pagesSet].map(p => sel.replace('.rd-fw ', '.rd-fw.fw-pg-' + p + ' ')).join(', '), decls);
  }
}
css += plain.join('\n') + '\n';
for (const [m, list] of medias) css += `${m} {\n${list.join('\n')}\n}\n`;
fs.writeFileSync(OUT, css);

const defined = new Set(['bg', 'panel', 'panel-2', 'panel-3', 'ink', 'ink-2', 'muted', 'line', 'line-2', 'accent', 'accent-bg', 'signal', 'signal-bg', 'ok', 'ok-bg', 'cool', 'cool-bg', 'violet', 'violet-bg', 'mono', 'serif', 'r', 'shadow']);
console.log(`pages ${pages}, classes used ${used.size}, rules ${rules.size}, conflicting redefinitions ${conflicts.size}, css ${Math.round(css.length / 1024)}KB`);
const missing = [...undefinedVars].filter(v => !defined.has(v));
if (conflicts.size) console.log('conflicts (first wins):', [...conflicts].slice(0, 12).join(' | '));
if (missing.length) console.log('tokens used but not defined:', missing.join(', '));
