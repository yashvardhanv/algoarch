// Builds web/src/frames.css: the original pages' panel styles, reduced to the classes that
// actually appear in captured widget frames, namespaced (.rd-fw .fw-*) and re-pointed at the
// app's own design tokens so the widgets follow the app theme.
//   node tools/content/build-frame-css.js [projectsDir] [captureDir]
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const PROJECTS = path.resolve(process.argv[2] || 'C:\\YASH\\CODES\\YASHVARDHAN_FAANG\\AI-System_design_DSA\\PROJECTS');
const CAP = path.resolve(process.argv[3] || path.join(ROOT, 'data', 'capture'));
const OUT = path.join(ROOT, 'web', 'src', 'frames.css');

// classes used by any recorded frame
const used = new Set();
function scan(n) {
  if (!n || typeof n === 'string') return;
  if (n.a && n.a.class) n.a.class.split(/\s+/).forEach(c => c && used.add(c));
  (n.k || []).forEach(scan);
}
for (const f of fs.readdirSync(CAP).filter(x => x.endsWith('.json') && !x.startsWith('_'))) {
  const j = JSON.parse(fs.readFileSync(path.join(CAP, f), 'utf8'));
  for (const p of j.panels || []) for (const fr of p.frames || []) scan(fr.b);
}
['panel-body'].forEach(c => used.add(c));

// css text from every original page
const rules = new Map(); // media|selector -> Map(declarations -> Set(page scopes))
let currentPage = '';
const conflicts = new Set();
const undefinedVars = new Set();

function stripComments(s) { return s.replace(/\/\*[\s\S]*?\*\//g, ''); }
function splitTop(s, sep) {
  const out = []; let depth = 0, cur = '';
  for (const ch of s) {
    if ('([{'.includes(ch)) depth++;
    if (')]}'.includes(ch)) depth--;
    if (ch === sep && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out;
}
function blocks(css) {
  const out = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const prelude = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    out.push({ prelude, body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}

function rewriteSelector(sel) {
  sel = sel.trim();
  if (!sel || /#|\[data-theme|^(html|body|:root)\b|^\*/.test(sel)) return null;
  const classes = [...sel.matchAll(/\.([A-Za-z_][\w-]*)/g)].map(m => m[1]);
  if (!classes.length || !classes.every(c => used.has(c))) return null;
  return '.rd-fw ' + sel.replace(/\.([A-Za-z_][\w-]*)/g, '.fw-$1');
}
function rewriteDecls(body) {
  return body.replace(/var\(--([\w-]+)/g, (m, n) => { undefinedVars.add(n); return 'var(--fw-' + n; }).trim();
}

function addRule(selector, decls, media) {
  const key = (media || '') + '|' + selector;
  if (!rules.has(key)) rules.set(key, new Map());
  const variants = rules.get(key);
  if (!variants.has(decls)) variants.set(decls, new Set());
  variants.get(decls).add(currentPage);
  if (variants.size > 1) conflicts.add(selector);
}

function processBlocks(css, media) {
  for (const b of blocks(css)) {
    if (/^@media/.test(b.prelude)) { processBlocks(b.body, b.prelude); continue; }
    if (/^@/.test(b.prelude)) continue; // keyframes/font-face/supports are not carried over
    const sels = splitTop(b.prelude, ',').map(rewriteSelector).filter(Boolean);
    if (!sels.length) continue;
    const decls = rewriteDecls(b.body);
    if (!decls) continue;
    for (const s of sels) addRule(s, decls, media);
  }
}

// the same scope id is stored with each widget (see convert.js) so page-specific rules apply only there
const scopeOf = (d, f) => (d + '-' + f.replace(/\.html$/, '')).replace(/[^\w-]/g, '-');
let pages = 0;
for (const d of ['dsa-faang-prep', 'system-design-prep', 'ai-master-prep', 'behavioral-prep']) {
  const dir = path.join(PROJECTS, d, 'visuals');
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.html'))) {
    const html = fs.readFileSync(path.join(dir, f), 'utf8');
    currentPage = scopeOf(d, f);
    for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) processBlocks(stripComments(m[1]), null);
    pages++;
  }
}

